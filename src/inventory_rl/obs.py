"""신경망에 넣기 전에 관측 크기를 맞춘다.

Serial-v0 관측은 원본 CoreEnv 가 만드는 15칸이다. 순서는 아래와 같다.

    [0]      직전 기간 수요 D
    [1]      미충족(백로그) U
    [2:5]    소매·유통·공장 보유 재고 X  (초기값 100, 100, 200)
    [5:13]   파이프라인. 발주 링크 (2,1) L=4 네 칸 + (3,2) L=4 네 칸
             (4,3) 은 L=0 이라 파이프라인에 안 들어간다.
    [13]     현재 기간 t (0~29)
    [14]     sentiment (goodwill 배율, 보통 0.2~2)

칸마다 숫자 크기가 다르다. 재고 200과 수요 20을 그대로 넣으면
신경망이 재고만 보고 수요를 거의 무시한다. 그래서 칸마다 나눠
대략 0~1 근처로 맞춘다.
"""

from __future__ import annotations

import numpy as np

# 위 15칸 각각을 나누는 값. 파이프라인은 발주량 스케일(80), t 는 에피소드 길이 30.
OBS_SCALE = np.array(
    [
        80.0,  # [0] 수요
        80.0,  # [1] 미충족
        100.0,  # [2] 소매 재고
        100.0,  # [3] 유통 재고
        200.0,  # [4] 공장 재고
        80.0, 80.0, 80.0, 80.0,  # [5:9]  소매로 오는 파이프라인 4칸
        80.0, 80.0, 80.0, 80.0,  # [9:13] 유통으로 오는 파이프라인 4칸
        30.0,  # [13] 기간 t
        1.0,  # [14] sentiment 는 이미 1 근처
    ],
    dtype=np.float32,
)


def scale_obs(obs: np.ndarray) -> np.ndarray:
    """관측 벡터를 OBS_SCALE 로 나눈다. 길이가 짧으면 앞부분만 쓴다."""
    obs = np.asarray(obs, dtype=np.float32).reshape(-1)
    return obs / OBS_SCALE[: obs.shape[0]]
